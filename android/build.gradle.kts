// Workaround: file_picker 11 skips the Kotlin plugin on AGP 9+, expecting
// AGP's built-in Kotlin, but this project has android.builtInKotlin=false
// (Flutter's template default). Without this its Kotlin code isn't compiled
// and the build fails with "cannot find symbol FilePickerPlugin".
// Remove when file_picker can be upgraded (needs flutter_secure_storage 10+
// for win32 6) or when builtInKotlin is turned on.
subprojects {
    if (name == "file_picker") {
        pluginManager.withPlugin("com.android.library") {
            pluginManager.apply("org.jetbrains.kotlin.android")
        }
        tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
            compilerOptions.jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }
}

tasks.register<Delete>("clean") {
    delete(rootProject.layout.buildDirectory)
}
