#!/usr/bin/env python3
"""Generates every app icon from the one drawing below.

Run from the repo root after changing the drawing:  python3 tool/make_icons.py
Needs ImageMagick (`magick`) for the PNGs.

Writes:
- Android adaptive icon (vector XML, API 26+), including the monochrome
  layer for themed icons (API 33+).
- Android legacy PNGs (older than API 26).
- Web icons and favicon.

The drawing uses the adaptive-icon canvas: 108 x 108, of which launchers
show the middle 72 x 72. Everything important sits inside the middle 66.
"""

import math
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
WEB = ROOT / "web"

LICHEN = "#6E7046"  # background, and the g
CREAM = "#EDE3CC"  # the jumper
SHADE = "#B9A983"  # ribbing and collar

# Shrinks the drawing around the centre so it fits the safe zone.
SCALE = 0.85

BODY = (
    "M46,27 Q54,33 62,27 C68,27 74,30 77,36 C81,46 85,58 86,70 L77.5,72.5 "
    "C76,62 73.5,53 71,47 C72.5,56 72.5,68 71,75 L70,82 L38,82 L37,75 "
    "C35.5,68 35.5,56 37,47 C34.5,53 32,62 30.5,72.5 L22,70 "
    "C23,58 27,46 31,36 C34,30 40,27 46,27 Z"
)
COLLAR = "M45.2,29.2 Q54,36.5 62.8,29.2"
CUFFS = "M85.6,65.6 L77,68.2 M22.4,65.6 L31,68.2"
HEM = " ".join(f"M{x},76.5 L{x},81.5" for x in range(41, 66, 4))

# The cursive g, drawn upright. It is slanted 8 degrees below, because
# Android vector drawables have no skew transform.
_G_UPRIGHT = (
    "M60,47 C58,42 50,41.5 47.5,46.5 C45,52 48,57.5 53,57.5 "
    "C57.5,57.5 60,53 60,47 L60,62 C60,68 56,71.5 52,70.5 "
    "C48.5,69.5 48.5,65.5 52,63.5 C56,61.2 62,60 67,57"
)


def _slant(path: str) -> str:
    k = math.tan(math.radians(-8))

    def point(m: re.Match) -> str:
        x, y = float(m.group(1)), float(m.group(2))
        return f"{x + k * (y - 56) - 1.5:.2f},{y - 1.5:.2f}"

    return re.sub(r"(-?[\d.]+),(-?[\d.]+)", point, path)


G = _slant(_G_UPRIGHT)

# (path, fill, stroke, stroke width) from back to front.
COLOUR_LAYERS = [
    (BODY, CREAM, CREAM, 2),
    (HEM, None, SHADE, 1.8),
    (COLLAR, None, SHADE, 1.8),
    (CUFFS, None, SHADE, 1.8),
    (G, None, LICHEN, 3.8),
]
# Themed icons are tinted one colour, so the jumper becomes an outline.
MONO_LAYERS = [
    (BODY, None, "#000000", 3),
    (HEM, None, "#000000", 1.8),
    (CUFFS, None, "#000000", 1.8),
    (G, None, "#000000", 3.8),
]


def vector_xml(layers) -> str:
    paths = ""
    for d, fill, stroke, width in layers:
        paths += (
            "        <path\n"
            f'            android:pathData="{d}"\n'
            + (f'            android:fillColor="{fill}"\n' if fill else "")
            + f'            android:strokeColor="{stroke}"\n'
            f'            android:strokeWidth="{width}"\n'
            '            android:strokeLineCap="round"\n'
            '            android:strokeLineJoin="round" />\n'
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/make_icons.py. Edit that, not this. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        "    <group\n"
        f'        android:scaleX="{SCALE}"\n'
        f'        android:scaleY="{SCALE}"\n'
        '        android:pivotX="54"\n'
        '        android:pivotY="54">\n'
        f"{paths}"
        "    </group>\n"
        "</vector>\n"
    )


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. Edit that, not this. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

COLORS_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. Edit that, not this. -->
<resources>
    <color name="ic_launcher_background">{LICHEN}</color>
</resources>
"""


def svg(size: int, view: tuple[float, float], corner: float = 0) -> str:
    """The colour icon as SVG. `view` is (origin, width) of a square crop."""
    origin, width = view
    art = ""
    for d, fill, stroke, w in COLOUR_LAYERS:
        art += (
            f'<path d="{d}" fill="{fill or "none"}" stroke="{stroke}" '
            f'stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'
        )
    t = 54 * (1 - SCALE)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="{origin} {origin} {width} {width}">'
        f'<rect x="{origin}" y="{origin}" width="{width}" height="{width}" '
        f'rx="{corner}" fill="{LICHEN}"/>'
        f'<g transform="translate({t:.2f},{t:.2f}) scale({SCALE})">{art}</g></svg>'
    )


def png(out: Path, size: int, view, corner: float = 0) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".svg") as f:
        f.write(svg(size, view, corner))
        f.flush()
        subprocess.run(
            ["magick", "-background", "none", f.name, "-strip", str(out)],
            check=True,
        )


def main() -> None:
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(ADAPTIVE_XML)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(
        vector_xml(COLOUR_LAYERS)
    )
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector_xml(MONO_LAYERS)
    )
    (RES / "values/ic_launcher_background.xml").write_text(COLORS_XML)

    shown = (18, 72)  # what a launcher shows of the 108 canvas
    for density, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        png(RES / f"mipmap-{density}/ic_launcher.png", size, shown, corner=16)

    png(WEB / "favicon.png", 32, shown, corner=16)
    for size in (192, 512):
        png(WEB / f"icons/Icon-{size}.png", size, shown)
        # Maskable icons may be cropped to the middle 80%, so leave more room.
        png(WEB / f"icons/Icon-maskable-{size}.png", size, (14, 80))


if __name__ == "__main__":
    main()
